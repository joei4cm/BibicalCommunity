const ZH_ABBR_KEYS = Object.keys(ZH_ABBR_TO_OSIS).sort((a, b) => b.length - a.length);

/** Exact Chinese abbr / full-name → OSIS, or null. */
export function osisFromZhToken(raw: string): string | null {
  const token = raw.trim().replace(/\s+/g, "");
  for (const key of ZH_ABBR_KEYS) {
    if (token === key) return ZH_ABBR_TO_OSIS[key] ?? null;
  }
  return null;
}

/**
 * Resolve a book token (zh abbr, OSIS, or localized full name) to OSIS id.
 * English aliases are handled by callers via normalizeBookKey when needed.
 */
export function resolveBookId(input: string): string | null {
  const raw = input.trim().replace(/\s+/g, "");
  if (!raw) return null;

  const zh = osisFromZhToken(raw);
  if (zh && getBook(zh)) return zh;

  const exact = getBook(raw);
  if (exact) return exact.id;

  const lower = raw.toLowerCase();
  for (const b of BOOK_LIST) {
    if (b.name.zh === raw || b.name.ja === raw) return b.id;
    if (b.name.en.replace(/\s+/g, "").toLowerCase() === lower) return b.id;
    if (b.id.toLowerCase() === lower) return b.id;
  }
  return null;
}
