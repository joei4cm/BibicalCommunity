#!/usr/bin/env bash
# Prepare a production wrangler config for live Cloudflare deploy.
#
# Required env:
#   CLOUDFLARE_API_TOKEN
#   CLOUDFLARE_ACCOUNT_ID
#
# Ensures D1 database `logoshome` + R2 bucket `logoshome-media` exist, then
# writes apps/api/wrangler.production.ci.toml with real IDs (gitignored).
#
# Prints: CF_PREPARE_OK path=<toml>
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API="$ROOT/apps/api"
SRC="$API/wrangler.production.toml"
OUT="$API/wrangler.production.ci.toml"
DB_NAME="logoshome"
BUCKET="logoshome-media"

if [[ -z "${CLOUDFLARE_API_TOKEN:-}" || -z "${CLOUDFLARE_ACCOUNT_ID:-}" ]]; then
  echo "FAIL: CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID are required"
  echo "CF_PREPARE_FAIL"
  exit 1
fi

export CLOUDFLARE_API_TOKEN CLOUDFLARE_ACCOUNT_ID

if [[ ! -f "$SRC" ]]; then
  echo "FAIL: missing $SRC"
  echo "CF_PREPARE_FAIL"
  exit 1
fi

echo "== cf-prepare-prod-config =="
echo "account=${CLOUDFLARE_ACCOUNT_ID:0:8}…"

cd "$API"

pick_db_id() {
  local json_file="$1"
  DB_NAME="$DB_NAME" python3 - "$json_file" <<'PY'
import json, os, sys
path = sys.argv[1]
name = os.environ["DB_NAME"]
try:
    rows = json.load(open(path))
except Exception:
    rows = []
if isinstance(rows, dict):
    rows = rows.get("result") or rows.get("databases") or []
for row in rows if isinstance(rows, list) else []:
    if isinstance(row, dict) and row.get("name") == name:
        print(row.get("uuid") or row.get("id") or "")
        break
PY
}

has_bucket() {
  local json_file="$1"
  BUCKET="$BUCKET" python3 - "$json_file" <<'PY'
import json, os, sys
path = sys.argv[1]
want = os.environ["BUCKET"]
try:
    rows = json.load(open(path))
except Exception:
    rows = []
if isinstance(rows, dict):
    rows = rows.get("buckets") or rows.get("result") or []
for row in rows if isinstance(rows, list) else []:
    if isinstance(row, dict) and (row.get("name") or row.get("Name")) == want:
        print("1")
        raise SystemExit
print("0")
PY
}

echo "== ensure D1 database ($DB_NAME) =="
pnpm exec wrangler d1 list --json > /tmp/cf-d1-list.json 2>/tmp/cf-d1-list.err || echo "[]" > /tmp/cf-d1-list.json
DB_ID=$(pick_db_id /tmp/cf-d1-list.json)

if [[ -z "$DB_ID" ]]; then
  echo "INFO: creating D1 database $DB_NAME"
  pnpm exec wrangler d1 create "$DB_NAME" 2>&1 | tee /tmp/cf-d1-create.log
  DB_ID=$(rg -o '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' /tmp/cf-d1-create.log | head -1 || true)
  if [[ -z "$DB_ID" ]]; then
    echo "FAIL: could not parse D1 database_id from create output"
    echo "CF_PREPARE_FAIL"
    exit 1
  fi
fi
echo "OK: D1 $DB_NAME → $DB_ID"

echo "== ensure R2 bucket ($BUCKET) =="
pnpm exec wrangler r2 bucket list --json > /tmp/cf-r2-list.json 2>/tmp/cf-r2-list.err || echo "[]" > /tmp/cf-r2-list.json
if [[ "$(has_bucket /tmp/cf-r2-list.json)" != "1" ]]; then
  echo "INFO: creating R2 bucket $BUCKET"
  if ! pnpm exec wrangler r2 bucket create "$BUCKET"; then
    pnpm exec wrangler r2 bucket list --json > /tmp/cf-r2-list.json 2>/tmp/cf-r2-list.err || echo "[]" > /tmp/cf-r2-list.json
    if [[ "$(has_bucket /tmp/cf-r2-list.json)" != "1" ]]; then
      echo "FAIL: R2 bucket $BUCKET missing after create"
      echo "CF_PREPARE_FAIL"
      exit 1
    fi
  fi
fi
echo "OK: R2 $BUCKET"

echo "== write $OUT =="
ACCOUNT_ID="$CLOUDFLARE_ACCOUNT_ID" DB_ID="$DB_ID" SRC="$SRC" OUT="$OUT" python3 <<'PY'
import os
from pathlib import Path
src = Path(os.environ["SRC"]).read_text()
account = os.environ["ACCOUNT_ID"]
db_id = os.environ["DB_ID"]
out = src.replace('account_id = "YOUR_CLOUDFLARE_ACCOUNT_ID"', f'account_id = "{account}"')
out = out.replace('database_id = "YOUR_D1_DATABASE_ID"', f'database_id = "{db_id}"')
if "YOUR_CLOUDFLARE_ACCOUNT_ID" in out or "YOUR_D1_DATABASE_ID" in out:
    raise SystemExit("placeholders remain after substitution")
header = "# GENERATED by scripts/cf-prepare-prod-config.sh — do not commit\n"
Path(os.environ["OUT"]).write_text(header + out)
print(f"wrote {os.environ['OUT']}")
PY

echo "CF_PREPARE_OK path=$OUT database_id=$DB_ID"
