#!/usr/bin/env bash
# Seed boot corpora (cuvs+nasb) into remote D1 via wrangler SQL (bypasses workers.dev bot).
# Tokens: LIVE_WORKERS_D1_CORPUS_OK | LIVE_WORKERS_D1_CORPUS_OPEN
# Does NOT close CORPUS_LIVE_R2_OK.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API_DIR="$ROOT/apps/api"
CFG_NAME="${1:-wrangler.temporary.toml}"
CFG="$API_DIR/$CFG_NAME"
ACCOUNT_TOML="${HOME}/.config/.wrangler/wrangler-temporary-account.toml"

echo "== D1 SQL-remote corpus boot seed (cfg=$CFG_NAME) =="

if [[ ! -f "$ACCOUNT_TOML" ]]; then
  echo "LIVE_WORKERS_D1_CORPUS_OPEN reason=no_temporary_account"
  echo "CORPUS_LIVE_R2_OPEN"
  exit 0
fi

API_TOKEN="$(python3 -c 'import re,sys; t=open(sys.argv[1]).read(); m=re.search(r"apiToken\s*=\s*\"([^\"]+)\"", t); print(m.group(1) if m else "")' "$ACCOUNT_TOML")"
ACCOUNT_ID="$(python3 -c 'import re,sys; t=open(sys.argv[1]).read(); m=re.search(r"^id\s*=\s*\"([^\"]+)\"", t, re.M); print(m.group(1) if m else "")' "$ACCOUNT_TOML")"
if [[ -z "$API_TOKEN" || -z "$ACCOUNT_ID" ]]; then
  echo "LIVE_WORKERS_D1_CORPUS_OPEN reason=temporary_account_unreadable"
  echo "CORPUS_LIVE_R2_OPEN"
  exit 0
fi
export CLOUDFLARE_API_TOKEN="$API_TOKEN"
export CLOUDFLARE_ACCOUNT_ID="$ACCOUNT_ID"

SQL_FILE="/tmp/d1-corpus-boot-seed.sql"
cd "$ROOT"
# Use package entry via pnpm filter so workspace resolution works.
pnpm --filter @logoshome/bible exec node --input-type=module <<'NODE' >"$SQL_FILE"
import { buildDemoDownloadPack } from "./dist/index.js";

const now = Date.now();
const lines = [
  "-- Generated by scripts/seed-d1-corpus-sql-remote.sh",
  "CREATE TABLE IF NOT EXISTS corpus_chapters (",
  "  translation_id TEXT NOT NULL,",
  "  book TEXT NOT NULL,",
  "  chapter INTEGER NOT NULL,",
  "  body_json TEXT NOT NULL,",
  "  updated_at INTEGER NOT NULL,",
  "  PRIMARY KEY (translation_id, book, chapter)",
  ");",
];

function esc(s) {
  return String(s).replace(/'/g, "''");
}

let total = 0;
for (const tid of ["cuvs", "nasb"]) {
  const pack = buildDemoDownloadPack(tid);
  for (const ch of pack.chapters) {
    const body = JSON.stringify({
      book: ch.book,
      chapter: ch.chapter,
      verses: ch.verses,
    });
    lines.push(
      `INSERT INTO corpus_chapters (translation_id, book, chapter, body_json, updated_at) VALUES ('${esc(tid)}', '${esc(ch.book)}', ${Number(ch.chapter)}, '${esc(body)}', ${now}) ` +
        `ON CONFLICT(translation_id, book, chapter) DO UPDATE SET body_json=excluded.body_json, updated_at=excluded.updated_at;`,
    );
    total += 1;
  }
}
lines.push(`SELECT translation_id, COUNT(*) AS n FROM corpus_chapters GROUP BY translation_id;`);
console.log(lines.join("\n"));
console.error(`generated_rows=${total}`);
NODE

echo "sql_file=$SQL_FILE bytes=$(wc -c <"$SQL_FILE")"

cd "$API_DIR"
if ! npx wrangler d1 execute logoshome --remote -c "$CFG_NAME" --file "$SQL_FILE" 2>&1 | tee /tmp/d1-sql-remote-seed.log; then
  echo "LIVE_WORKERS_D1_CORPUS_OPEN reason=sql_remote_execute_failed"
  echo "CORPUS_LIVE_R2_OPEN"
  exit 0
fi

COUNTS="$(npx wrangler d1 execute logoshome --remote -c "$CFG_NAME" --command \
  "SELECT translation_id, COUNT(*) AS n FROM corpus_chapters GROUP BY translation_id;" \
  --json 2>/tmp/d1-sql-remote-counts.err || true)"
echo "$COUNTS" | head -c 800; echo

parse_count() {
  local tid="$1"
  printf '%s' "$COUNTS" | python3 -c '
import sys,json
tid=sys.argv[1]
raw=sys.stdin.read()
try:
  data=json.loads(raw)
except Exception:
  print(0); raise SystemExit
rows=[]
if isinstance(data, list):
  for block in data:
    if isinstance(block, dict):
      rows.extend(block.get("results") or [])
elif isinstance(data, dict):
  rows=data.get("results") or []
n=0
for r in rows:
  got=str(r.get("translation_id") or r.get("translationId") or "")
  if got==tid:
    n=int(r.get("n") or r.get("COUNT(*)") or 0)
print(n)
' "$tid" 2>/dev/null || echo 0
}

CUVS_N="$(parse_count cuvs)"
NASB_N="$(parse_count nasb)"

echo "d1-sql-remote counts cuvs=$CUVS_N nasb=$NASB_N"

if [[ "$CUVS_N" -gt 0 && "$NASB_N" -gt 0 ]]; then
  echo "LIVE_WORKERS_D1_CORPUS_OK source=sql-remote cuvs=$CUVS_N nasb=$NASB_N"
else
  echo "LIVE_WORKERS_D1_CORPUS_OPEN reason=seed_counts_low cuvs=$CUVS_N nasb=$NASB_N"
fi
echo "CORPUS_LIVE_R2_OPEN reason=d1_sql_remote_only need=production_R2"
